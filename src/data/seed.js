function plan(p) {
  const v = venueByName(p.venue);
  return {
    durationMin: 90,
    status: 'upcoming',
    audience: 'nearby',
    attendees: [],
    map: v ? v.map : [50, 50],
    km: v ? v.km : 2,
    area: v ? v.area : 'Jubilee Hills',
    ...p,
  };
}

